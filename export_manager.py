"""Exports: XLSX, DOCX, PDF, SQL, CSV, JSON.

All exports are built from the *current* project state (i.e. after review and
edits in the preview tabs) - nothing is cached between edits and downloads.
"""
from __future__ import annotations

import io
import re
from typing import Any

import pandas as pd

from config import APP_NAME, STATUS_CONFIRMED, STATUS_MISSING, STATUS_REQUIRES_VALIDATION, STATUS_SUGGESTED
from documentation_generator import build_document
from models import (JOIN_FIELDS, MAPPING_FIELDS, OPEN_QUESTION_FIELDS, SOURCE_METADATA_FIELDS, TABLE_MAPPING_FIELDS,
                    TARGET_FIELDS)
from snowflake_sql_generator import SQL_LABELS, combined_script
from utils.text_utils import clean_str

STATUS_FILL = {STATUS_CONFIRMED: "C8E6C9", STATUS_SUGGESTED: "FFF59D",
               STATUS_REQUIRES_VALIDATION: "FFCC80", STATUS_MISSING: "EF9A9A"}


def safe_name(name: str) -> str:
    return re.sub(r"[^A-Za-z0-9_-]+", "_", clean_str(name) or "mapping").strip("_")[:60]


# --------------------------------------------------------------------------- simple formats
def to_sql(project) -> bytes:
    return combined_script(project.sql).encode("utf-8")


def to_csv(project) -> bytes:
    return project.df("column_mappings", MAPPING_FIELDS).to_csv(index=False).encode("utf-8-sig")


def to_json(project) -> bytes:
    return project.to_json(include_versions=False).encode("utf-8")


def to_project_file(project) -> bytes:
    """Full project including version snapshots - reopen with 'Open project'."""
    return project.to_json(include_versions=True).encode("utf-8")


# --------------------------------------------------------------------------- Excel
def _grain_frame(project) -> pd.DataFrame:
    rows = []
    for erp, g in project.grain.items():
        rows.append({"source_erp": erp, "grain_table": g.get("grain_table"),
                     "grain_keys": ", ".join(g.get("grain_keys", [])), "grain_description": g.get("grain_description"),
                     "dedup_partition": ", ".join(g.get("dedup_partition", [])),
                     "dedup_order": ", ".join(g.get("dedup_order", [])), "status": g.get("status"),
                     "confidence": g.get("confidence"), "reasoning": g.get("reasoning"),
                     "warnings": " | ".join(g.get("warnings", []))})
    return pd.DataFrame(rows)


def to_xlsx(project) -> bytes:
    from openpyxl.styles import Alignment, Font, PatternFill
    from openpyxl.utils import get_column_letter

    c = project.config
    summary = pd.DataFrame([
        ["Project", c.get("project_name")], ["Source ERP(s)", ", ".join(project.erps)],
        ["Module", c.get("source_module")], ["Business process", c.get("business_process")],
        ["Target", ".".join(x for x in (c.get("target_database"), c.get("target_schema"), c.get("target_object")) if x)],
        ["Mapping type", c.get("mapping_type")], ["History", c.get("history_requirement")],
        ["Expected grain", c.get("expected_grain")], ["Updated", project.updated_at],
        ["Generated by", APP_NAME],
    ] + [[f"Status: {s}", sum(1 for m in project.column_mappings if m.get("status") == s)]
         for s in STATUS_FILL], columns=["Item", "Value"])
    trans = project.df("column_mappings", MAPPING_FIELDS)[
        ["target_column", "source_erp", "transformation_type", "transformation_logic"]].copy()
    trans["explanation"] = [m.get("transformation_note", "") for m in project.column_mappings] if project.column_mappings else []
    sql_rows = [{"script": SQL_LABELS.get(k, k), "line": i + 1, "sql": line}
                for k, v in project.sql.items() for i, line in enumerate(v.splitlines())]
    sheets = {
        "Summary": summary,
        "Source Tables": project.df("table_mapping", TABLE_MAPPING_FIELDS),
        "Column Mapping": project.df("column_mappings", MAPPING_FIELDS),
        "Joins": project.df("joins", JOIN_FIELDS),
        "Data Grain": _grain_frame(project),
        "Transformations": trans,
        "Snowflake SQL": pd.DataFrame(sql_rows),
        "Open Questions": project.df("open_questions", OPEN_QUESTION_FIELDS),
        "Validation": pd.DataFrame(project.validation_issues),
        "Source Metadata": project.df("source_metadata", SOURCE_METADATA_FIELDS),
        "Target Requirements": project.df("target_columns", TARGET_FIELDS),
    }
    buf = io.BytesIO()
    with pd.ExcelWriter(buf, engine="openpyxl") as xw:
        for name, frame in sheets.items():
            frame = frame.copy()
            frame.to_excel(xw, sheet_name=name[:31], index=False)
            ws = xw.sheets[name[:31]]
            ws.freeze_panes = "A2"
            for cell in ws[1]:
                cell.font = Font(bold=True, color="FFFFFF")
                cell.fill = PatternFill("solid", fgColor="1F3A5F")
                cell.alignment = Alignment(vertical="center", wrap_text=True)
            for idx, col in enumerate(frame.columns, 1):
                width = min(max([len(str(col))] + [len(str(v)) for v in frame[col].head(200).tolist()]) + 2, 70)
                ws.column_dimensions[get_column_letter(idx)].width = max(width, 10)
            if name == "Snowflake SQL":
                ws.column_dimensions["C"].width = 140
                for row in ws.iter_rows(min_row=2, min_col=3, max_col=3):
                    row[0].font = Font(name="Consolas", size=9)
            if "status" in frame.columns:
                sidx = list(frame.columns).index("status") + 1
                for r in range(2, len(frame) + 2):
                    cell = ws.cell(row=r, column=sidx)
                    if cell.value in STATUS_FILL:
                        cell.fill = PatternFill("solid", fgColor=STATUS_FILL[cell.value])
            if len(frame):
                ws.auto_filter.ref = ws.dimensions
    return buf.getvalue()


# --------------------------------------------------------------------------- Word
def to_docx(project) -> bytes:
    from docx import Document
    from docx.enum.section import WD_ORIENT
    from docx.oxml import OxmlElement
    from docx.oxml.ns import qn
    from docx.shared import Cm, Pt, RGBColor

    doc_model = build_document(project)
    d = Document()
    sec = d.sections[0]
    sec.orientation = WD_ORIENT.LANDSCAPE
    sec.page_width, sec.page_height = Cm(29.7), Cm(21.0)
    for side in ("left_margin", "right_margin", "top_margin", "bottom_margin"):
        setattr(sec, side, Cm(1.8))
    style = d.styles["Normal"]
    style.font.name = "Calibri"
    style.font.size = Pt(10.5)

    d.add_heading(doc_model["title"], level=0)
    p = d.add_paragraph(f"Generated by {APP_NAME}. Recommendations (Suggested / Requires Validation) are not "
                        "verified ERP relationships.")
    p.runs[0].italic = True

    def shade(cell, hex_color):
        tcPr = cell._tc.get_or_add_tcPr()
        shd = OxmlElement("w:shd")
        shd.set(qn("w:val"), "clear")
        shd.set(qn("w:color"), "auto")
        shd.set(qn("w:fill"), hex_color)
        tcPr.append(shd)

    for s in doc_model["sections"]:
        d.add_heading(s["title"], level=1)
        for b in s["blocks"]:
            if b["type"] == "h3":
                d.add_heading(b["text"], level=2)
            elif b["type"] == "p":
                d.add_paragraph(b["text"])
            elif b["type"] == "bullets":
                for i in b["items"]:
                    d.add_paragraph(i, style="List Bullet")
            elif b["type"] == "code":
                for chunk in _chunks(b["text"], 120):
                    para = d.add_paragraph()
                    para.paragraph_format.space_after = Pt(0)
                    run = para.add_run(chunk)
                    run.font.name = "Consolas"
                    run.font.size = Pt(7.5)
                    run.font.color.rgb = RGBColor(0x1F, 0x3A, 0x5F)
            elif b["type"] == "table":
                if not b["rows"]:
                    d.add_paragraph("No rows.").runs[0].italic = True
                    continue
                t = d.add_table(rows=1, cols=len(b["columns"]))
                t.style = "Table Grid"
                for i, col in enumerate(b["columns"]):
                    cell = t.rows[0].cells[i]
                    cell.text = col
                    shade(cell, "1F3A5F")
                    for r in cell.paragraphs[0].runs:
                        r.font.bold, r.font.size = True, Pt(8)
                        r.font.color.rgb = RGBColor(0xFF, 0xFF, 0xFF)
                status_idx = b["columns"].index("Status") if "Status" in b["columns"] else None
                for row in b["rows"]:
                    cells = t.add_row().cells
                    for i, v in enumerate(row):
                        cells[i].text = v
                        for r in cells[i].paragraphs[0].runs:
                            r.font.size = Pt(8)
                        if status_idx is not None and i == status_idx and v in STATUS_FILL:
                            shade(cells[i], STATUS_FILL[v])
                d.add_paragraph()
    buf = io.BytesIO()
    d.save(buf)
    return buf.getvalue()


def _chunks(text: str, size: int) -> list[str]:
    """One paragraph per line keeps long SQL readable; very long lines are wrapped."""
    out = []
    for line in text.splitlines() or [""]:
        while len(line) > size:
            out.append(line[:size])
            line = "    " + line[size:]
        out.append(line)
    return out


# --------------------------------------------------------------------------- PDF
def to_pdf(project) -> bytes:
    from xml.sax.saxutils import escape

    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4, landscape
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
    from reportlab.lib.units import cm
    from reportlab.platypus import (KeepTogether, Paragraph, Preformatted, SimpleDocTemplate, Spacer, Table,
                                    TableStyle)

    doc_model = build_document(project)
    buf = io.BytesIO()
    page = landscape(A4)
    doc = SimpleDocTemplate(buf, pagesize=page, leftMargin=1.5 * cm, rightMargin=1.5 * cm, topMargin=1.5 * cm,
                            bottomMargin=1.5 * cm, title=doc_model["title"], author=APP_NAME)
    ss = getSampleStyleSheet()
    body = ParagraphStyle("body", parent=ss["BodyText"], fontSize=9, leading=12)
    cell = ParagraphStyle("cell", parent=body, fontSize=7, leading=8.5)
    head = ParagraphStyle("head", parent=cell, textColor=colors.white, fontName="Helvetica-Bold")
    code = ParagraphStyle("code", fontName="Courier", fontSize=6.5, leading=7.8, textColor=colors.HexColor("#1F3A5F"))
    h1 = ParagraphStyle("h1", parent=ss["Heading1"], fontSize=15, textColor=colors.HexColor("#1F3A5F"), spaceBefore=10)
    h2 = ParagraphStyle("h2", parent=ss["Heading2"], fontSize=11.5, textColor=colors.HexColor("#1F3A5F"))
    width = page[0] - 3 * cm

    story = [Paragraph(escape(doc_model["title"]), ss["Title"]),
             Paragraph(escape(f"Generated by {APP_NAME}. Suggested / Requires Validation items are recommendations, "
                              "not verified ERP relationships."), body), Spacer(1, 8)]
    for s in doc_model["sections"]:
        story.append(Paragraph(escape(s["title"]), h1))
        for b in s["blocks"]:
            if b["type"] == "h3":
                story.append(Paragraph(escape(b["text"]), h2))
            elif b["type"] == "p":
                story.append(Paragraph(escape(b["text"]), body))
            elif b["type"] == "bullets":
                for i in b["items"]:
                    story.append(Paragraph("• " + escape(i), body))
            elif b["type"] == "code":
                story.append(Preformatted("\n".join(_chunks(b["text"], 175)), code))
            elif b["type"] == "table":
                if not b["rows"]:
                    story.append(Paragraph("<i>No rows.</i>", body))
                    continue
                ncol = len(b["columns"])
                weights = [max([len(b["columns"][i])] + [min(len(r[i]), 60) for r in b["rows"]]) for i in range(ncol)]
                tot = sum(weights) or 1
                widths = [max(width * w / tot, 1.4 * cm) for w in weights]
                scale = width / sum(widths)
                widths = [w * scale for w in widths]
                data = [[Paragraph(escape(c), head) for c in b["columns"]]] + \
                       [[Paragraph(escape(v[:1500]), cell) for v in r] for r in b["rows"]]
                t = Table(data, colWidths=widths, repeatRows=1)
                style = [("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1F3A5F")),
                         ("GRID", (0, 0), (-1, -1), 0.3, colors.HexColor("#B0BEC5")),
                         ("VALIGN", (0, 0), (-1, -1), "TOP"),
                         ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F5F7FA")])]
                if "Status" in b["columns"]:
                    si = b["columns"].index("Status")
                    for ri, r in enumerate(b["rows"], 1):
                        if r[si] in STATUS_FILL:
                            style.append(("BACKGROUND", (si, ri), (si, ri), colors.HexColor("#" + STATUS_FILL[r[si]])))
                t.setStyle(TableStyle(style))
                story.append(t)
            story.append(Spacer(1, 5))

    def footer(canvas, d):
        canvas.saveState()
        canvas.setFont("Helvetica", 7)
        canvas.setFillColor(colors.grey)
        canvas.drawString(1.5 * cm, 0.8 * cm, f"{APP_NAME} - {project.config.get('project_name')}")
        canvas.drawRightString(page[0] - 1.5 * cm, 0.8 * cm, f"Page {d.page}")
        canvas.restoreState()

    doc.build(story, onFirstPage=footer, onLaterPages=footer)
    return buf.getvalue()


