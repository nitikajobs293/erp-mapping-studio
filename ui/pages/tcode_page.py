from __future__ import annotations

import pandas as pd
import streamlit as st

from erpdm.constants import SQL_DIALECTS
from erpdm.db.models import GeneratedArtifact
from erpdm.services.dataflow import flow_for_transaction
from erpdm.services.metadata import get_erp
from erpdm.services.modelling import recommend_model
from erpdm.services.sqlgen import generate_sql
from erpdm.services.tcode import analyze_transaction, find_similar_codes
from ui import components as ui
from ui import workflow_ui as wui


def render() -> None:
    st.title("🧾 T-Code / Transaction Intelligence")
    code = ui.need_erp()
    if not code:
        return
    w = ui.wf()
    c1, c2, c3, c4 = st.columns([1.2, 1, 1, 1])
    tcode = c1.text_input("T-Code / transaction / screen", value=w.tcode or "", placeholder="e.g. IQ09").strip().upper()
    dialect = c2.selectbox("SQL dialect", list(SQL_DIALECTS), index=list(SQL_DIALECTS).index(w.dialect))
    include_pending = c3.toggle("Include pending joins", value=w.include_pending,
                                help="Also use AI-inferred / SQL-parsed joins that are not yet approved.")
    include_optional = c4.toggle("Include optional tables", value=False)
    if not tcode:
        st.caption("Enter a transaction code. The analysis is assembled from the metadata repository — "
                   "not generated by AI.")
        return
    with ui.db() as s:
        erp = get_erp(s, code)
        a = analyze_transaction(s, erp, tcode, dialect, include_optional, include_pending)
        if a is None:
            st.warning(f"**{tcode}** is not in the {erp.name} repository.")
            similar = find_similar_codes(s, erp.id, tcode)
            if similar:
                st.write("Similar codes: " + ", ".join(f"`{x}`" for x in similar))
            st.info("To add it, upload a T-code list (with table assignments) or a metadata package in "
                    "**Metadata Management**. The platform does not guess which tables a transaction uses.")
            return
        tx = a.transaction
        st.subheader(f"{tx.code} — {tx.name}")
        st.caption(f"{ui.status_badge(tx.validation_status, tx.confidence)} · source: {ui.trusted_label(tx.source_type)}")
        tabs = st.tabs(["Overview", "Tables & columns", "Relationships & ER diagram", "SQL", "Model & incremental load",
                        "Data flow"])
        with tabs[0]:
            m = st.columns(4)
            m[0].metric("Module", tx.module.code if tx.module else "—")
            m[1].metric("Process", (tx.process.name if tx.process else "—")[:28])
            m[2].metric("Backend tables", len(a.tables))
            m[3].metric("Joins", len(a.plan.edges))
            st.markdown(f"**Description:** {tx.description or '—'}")
            st.markdown(f"**Business purpose:** {tx.business_purpose or '—'}")
            st.markdown(f"**Business object:** {tx.business_object or '—'}")
            st.markdown(f"**Business logic:** {tx.business_logic or '—'}")
            if tx.app_components:
                st.markdown("**Application components / views / function modules:**")
                st.json(tx.app_components)
            st.markdown("**Verification summary**")
            ui.df(pd.DataFrame(a.verification, columns=["Item", "Status"]))
            if erp.landscape_notes:
                st.warning(erp.landscape_notes)
        with tabs[1]:
            ui.df([{"Table": t.name, "Role": t.role, "Description": t.description, "Class": t.table_class,
                    "Primary key": ", ".join(t.primary_key), "Columns used": ", ".join(t.columns_used),
                    "Notes": t.notes, "Validation": ui.status_badge(t.validation_status, t.confidence)} for t in a.tables])
            st.markdown("**Adjust the required columns** (the SQL, model and workflow update from this selection)")
            picked = wui.column_picker(s, erp, [t.name for t in a.tables], a.columns, key=f"tc_{tx.code}")
            columns, plan, sql = a.columns, a.plan, a.sql
            if picked and {(c.table, c.column) for c in picked} != {(c.table, c.column) for c in a.columns}:
                columns = picked
                plan = wui.replan(s, erp, columns, a.plan.root_table, include_pending=include_pending)
                sql = generate_sql(s, erp, plan, columns, dialect, raw_schema=erp.code)
                st.success(f"Selection updated: {len(columns)} columns from {len(plan.tables)} tables.")
        with tabs[2]:
            wui.plan_table(plan)
            st.markdown("**All stored relationships among these tables**")
            ui.df(a.relationships)
            wui.er_diagram(s, erp, plan, columns)
        with tabs[3]:
            st.code(sql.sql, language="sql")
            st.download_button("Download SQL", sql.sql, file_name=f"{erp.code}_{tx.code}.sql", mime="text/plain")
            with st.expander("Join explanations", expanded=True):
                for x in sql.join_explanations:
                    st.markdown(f"- {x}")
            with st.expander("Filters · duplicates · nulls"):
                for x in sql.filter_explanations + sql.duplicate_handling + sql.null_handling:
                    st.markdown(f"- {x}")
            with st.expander("Performance considerations"):
                for x in sql.performance_notes:
                    st.markdown(f"- {x}")
            with st.expander("Validation queries"):
                for k, v in sql.validation_queries.items():
                    st.markdown(f"**{k}**")
                    st.code(v, language="sql")
        with tabs[4]:
            rec = recommend_model(s, erp, plan, columns) if plan is not a.plan else a.model
            st.markdown("**Recommended Snowflake model**")
            ui.df([{"Model": m.name, "Kind": m.kind, "Grain": m.grain, "SCD": m.scd_type,
                    "Natural key": ", ".join(m.natural_key), "Surrogate key": m.surrogate_key,
                    "Sources": ", ".join(m.source_tables), "Rationale": m.rationale} for m in rec.models])
            st.markdown("**Incremental load strategy per source table**")
            ui.df([{"Table": x.table, "Strategy": x.strategy, "Unique key": ", ".join(x.unique_key),
                    "Watermark": ", ".join(x.watermark) or "—", "Reliable timestamp": x.watermark_reliable,
                    "Lookback": x.lookback, "Change tracking": x.change_tracking, "Hard deletes": x.hard_delete,
                    "Full refresh": x.full_refresh_cadence} for x in rec.strategies])
            for n in rec.notes:
                st.caption(f"ℹ️ {n}")
        with tabs[5]:
            ui.graphviz(flow_for_transaction(s, erp, tx, plan.tables, w))
        st.divider()
        if st.button("💾 Save SQL to history", key="tc_save"):
            s.add(GeneratedArtifact(kind="sql", name=f"{erp.code}_{tx.code}", erp_id=erp.id, content=sql.sql,
                                    created_by=ui.user().username, meta={"dialect": dialect}))
            st.toast("SQL saved")
        w.dialect, w.include_pending = dialect, include_pending
        wui.send_to_workflow(plan, columns, tcode=tx.code, sql=sql.sql, sql_meta=sql.model_dump(), key="tc_send")
