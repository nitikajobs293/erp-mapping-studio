"""dbt project generator (Snowflake): sources, staging, intermediate, marts, snapshots, tests, macros.

Generated from repository metadata + a JoinPlan + selected columns + a ModelRecommendation, so every
model, join and test traces back to stored (and provenance-labelled) metadata.
"""
from __future__ import annotations

import io
import re
import zipfile
from dataclasses import dataclass, field
from datetime import datetime, timezone

import yaml
from sqlalchemy.orm import Session

from erpdm.config import get_settings
from erpdm.db.models import ERPSystem, ERPTable, GeneratedArtifact
from erpdm.schemas import JoinPlan, SelectedColumn
from erpdm.services.audit import audit
from erpdm.services.metadata import get_column, get_table
from erpdm.services.modelling import IncrementalStrategy, ModelRecommendation, incremental_strategy
from erpdm.services.sqlgen import snake
from erpdm.services.typemap import staging_expression


@dataclass
class DbtOptions:
    project_name: str = "erp_analytics"
    raw_database: str = "RAW"
    raw_schema: str | None = None
    loaded_at_column: str | None = None
    cdc_deleted_column: str | None = None      # e.g. _fivetran_deleted / _deleted / IS_DELETED
    cdc_operation_column: str | None = None    # e.g. _op ('D' = delete)
    materialization: str = "incremental"       # incremental | table | view
    scd_type: str | None = None                # override: SCD1 | SCD2
    lookback_days: int = 3
    freshness_warn_hours: int = 24
    freshness_error_hours: int = 48
    language_key: str | None = None
    exclude_soft_deleted: bool = False
    generated_sql: str | None = None


@dataclass
class DbtProject:
    files: dict[str, str] = field(default_factory=dict)
    model_names: list[str] = field(default_factory=list)
    notes: list[str] = field(default_factory=list)

    def to_zip(self) -> bytes:
        buf = io.BytesIO()
        with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
            for path, content in sorted(self.files.items()):
                z.writestr(path, content)
        return buf.getvalue()


def _yaml(obj) -> str:
    return yaml.safe_dump(obj, sort_keys=False, allow_unicode=True, width=120)


def stg_column_name(table: ERPTable, col_name: str) -> str:
    """Deterministic staging name: business name if unique within table, else lowercase technical name."""
    col = get_column(table, col_name)
    if col is None:
        return snake(col_name)
    if col.business_name:
        cand = snake(col.business_name)
        dup = [c for c in table.columns if c.business_name and snake(c.business_name) == cand]
        if len(dup) == 1:
            return cand
    return snake(col.name)


def _src_name(erp: ERPSystem) -> str:
    return snake(erp.code)


def _desc(s: str | None) -> str:
    return (s or "").replace("\n", " ").strip()


def generate_dbt_project(session: Session, erp: ERPSystem, plan: JoinPlan, columns: list[SelectedColumn],
                         rec: ModelRecommendation, opts: DbtOptions | None = None) -> DbtProject:
    opts = opts or DbtOptions()
    settings = get_settings()
    loaded_at = opts.loaded_at_column or settings.raw_loaded_at_column
    lang = opts.language_key or erp.default_language_key or settings.default_language_key
    src = _src_name(erp)
    raw_schema = opts.raw_schema or erp.code
    client = (erp.client_column or "").upper()
    proj = DbtProject()
    tables: dict[str, ERPTable] = {t: get_table(session, erp.id, t) for t in plan.tables}
    root = tables[plan.root_table]
    # Bring in the status table if the root's soft-delete rule needs it.
    status_tbl = None
    if root.soft_delete_rule and "JEST" in root.soft_delete_rule and "JEST" not in tables:
        status_tbl = get_table(session, erp.id, "JEST")
        if status_tbl:
            tables["JEST"] = status_tbl
    elif "JEST" in tables:
        status_tbl = tables["JEST"]
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    header = (f"-- Generated by ERP Data Modelling Intelligence Platform on {stamp}\n"
              f"-- ERP: {erp.name} ({erp.code}). Review provenance in models/*.yml before production use.\n")

    # ------------------------------------------------------------------ project files
    proj.files["dbt_project.yml"] = _yaml({
        "name": opts.project_name, "version": "1.0.0", "config-version": 2, "profile": opts.project_name,
        "model-paths": ["models"], "snapshot-paths": ["snapshots"], "macro-paths": ["macros"],
        "test-paths": ["tests"], "analysis-paths": ["analyses"],
        "vars": {"erp_language_key": lang, "lookback_days": opts.lookback_days, "loaded_at_column": loaded_at},
        "models": {opts.project_name: {
            "staging": {"+materialized": "view", "+schema": "staging"},
            "intermediate": {"+materialized": "ephemeral" if opts.materialization == "view" else "view",
                             "+schema": "intermediate"},
            "marts": {"+materialized": "table", "+schema": "marts"}}},
        "snapshots": {opts.project_name: {"+target_schema": "snapshots"}},
    })
    proj.files["packages.yml"] = _yaml({"packages": [{"package": "dbt-labs/dbt_utils", "version": [">=1.1.0", "<2.0.0"]}]})
    proj.files["profiles.example.yml"] = _yaml({opts.project_name: {"target": "dev", "outputs": {"dev": {
        "type": "snowflake", "account": "{{ env_var('SNOWFLAKE_ACCOUNT') }}", "user": "{{ env_var('SNOWFLAKE_USER') }}",
        "password": "{{ env_var('SNOWFLAKE_PASSWORD') }}", "role": "{{ env_var('SNOWFLAKE_ROLE') }}",
        "warehouse": "{{ env_var('SNOWFLAKE_WAREHOUSE') }}", "database": settings.target_database,
        "schema": "dbt_dev", "threads": 4}}}})

    # ------------------------------------------------------------------ macros
    proj.files["macros/erp_to_date.sql"] = (
        "{% macro erp_to_date(col) -%}\n"
        "    try_to_date(nullif(nullif(trim({{ col }}), ''), '00000000'), 'YYYYMMDD')\n"
        "{%- endmacro %}\n")
    proj.files["macros/erp_blank_to_null.sql"] = (
        "{% macro erp_blank_to_null(col) -%}\n    nullif(trim({{ col }}), '')\n{%- endmacro %}\n")
    proj.files["macros/generate_schema_name.sql"] = (
        "{% macro generate_schema_name(custom_schema_name, node) -%}\n"
        "    {%- if custom_schema_name is none -%}{{ target.schema }}\n"
        "    {%- elif target.name == 'prod' -%}{{ custom_schema_name | trim }}\n"
        "    {%- else -%}{{ target.schema }}_{{ custom_schema_name | trim }}{%- endif -%}\n"
        "{%- endmacro %}\n")

    # ------------------------------------------------------------------ sources
    src_tables = []
    for t in tables.values():
        strat = incremental_strategy(erp, t)
        entry = {"name": t.name, "description": _desc(t.description) + f" [provenance: {t.source_type}, "
                 f"{t.validation_status}, confidence {t.confidence:.2f}]",
                 "loaded_at_field": loaded_at,
                 "columns": [{"name": c.name, "description": _desc(c.description)}
                             for c in t.columns if c.is_pk]}
        if t.table_class in ("config", "text"):
            entry["freshness"] = None
        src_tables.append(entry)
        del strat
    proj.files[f"models/staging/{src}/_{src}__sources.yml"] = _yaml({"version": 2, "sources": [{
        "name": src, "description": f"{erp.name} raw replicated tables. Extraction: {erp.extraction_method or 'n/a'}",
        "database": opts.raw_database, "schema": raw_schema,
        "freshness": {"warn_after": {"count": opts.freshness_warn_hours, "period": "hour"},
                      "error_after": {"count": opts.freshness_error_hours, "period": "hour"}},
        "tables": src_tables}]})

    # ------------------------------------------------------------------ staging
    stg_models_yml = []
    selected_by_table: dict[str, set[str]] = {}
    for c in columns:
        selected_by_table.setdefault(c.table.upper(), set()).add(c.column.upper())
    for t in tables.values():
        model = f"stg_{src}__{t.name.lower()}"
        needed = _needed_columns(t, plan, selected_by_table, client)
        lines = []
        for col in t.columns:
            if col.name.upper() not in needed:
                continue
            expr, _ = staging_expression(col.name, col.data_type, col.length, col.decimals)
            if (col.data_type or "").upper() == "DATS":
                expr = f"{{{{ erp_to_date('{col.name}') }}}}"
            lines.append(f"        {expr} as {stg_column_name(t, col.name)}")
        if t.soft_delete_rule and "EXISTS" not in t.soft_delete_rule.upper():
            rule = t.soft_delete_rule.replace("{alias}.", "")
            lines.append(f"        coalesce({rule}, false) as is_deleted")
        lines.append(f"        {loaded_at} as _loaded_at")
        where = []
        if opts.cdc_deleted_column:
            where.append(f"not coalesce({opts.cdc_deleted_column}, false)")
        if opts.cdc_operation_column:
            where.append(f"coalesce({opts.cdc_operation_column}, '') <> 'D'")
        sql = header + (
            f"-- Staging for {t.name}: {_desc(t.description)}\n"
            "-- Renames to business names, casts ERP types, converts blanks/'00000000' to NULL.\n\n"
            f"with source as (\n\n    select * from {{{{ source('{src}', '{t.name}') }}}}\n"
            + (f"    where {' and '.join(where)}\n" if where else "") +
            "\n),\n\nrenamed as (\n\n    select\n" + ",\n".join(lines) + "\n    from source\n\n)\n\nselect * from renamed\n")
        proj.files[f"models/staging/{src}/{model}.sql"] = sql
        proj.model_names.append(model)
        pk_names = [stg_column_name(t, k) for k in t.primary_key if k.upper() in needed]
        cols_yml = []
        for col in t.columns:
            if col.name.upper() not in needed:
                continue
            entry = {"name": stg_column_name(t, col.name),
                     "description": f"{t.name}.{col.name} — {_desc(col.description)}"}
            if col.is_pk:
                entry["tests"] = ["not_null"]
            cols_yml.append(entry)
        model_yml = {"name": model, "description": _desc(t.description), "columns": cols_yml}
        if len(pk_names) > 1:
            model_yml["tests"] = [{"dbt_utils.unique_combination_of_columns": {"combination_of_columns": pk_names}}]
        elif len(pk_names) == 1:
            cols_yml[[c["name"] for c in cols_yml].index(pk_names[0])]["tests"] = ["not_null", "unique"]
        stg_models_yml.append(model_yml)
    proj.files[f"models/staging/{src}/_{src}__models.yml"] = _yaml({"version": 2, "models": stg_models_yml})

    # ------------------------------------------------------------------ intermediate
    entity = rec.entity
    int_name = f"int_{entity}__joined"
    alias_tbl = {a: t for t, a in plan.aliases.items()}

    def translate(cond: str) -> str:
        def sub(m):
            a, c = m.group(1), m.group(2)
            if a in alias_tbl:
                return f"{a}.{stg_column_name(tables[alias_tbl[a]], c)}"
            return m.group(0)
        out = re.sub(r"\b([a-z_][a-z0-9_]*)\.([A-Za-z0-9_/]+)\b", sub, cond)
        return out.replace(f"'{lang}'", "'{{ var(\"erp_language_key\") }}'")

    ra = plan.aliases[plan.root_table]
    ctes = [f"{plan.aliases[t]} as (\n    select * from {{{{ ref('stg_{src}__{t.lower()}') }}}}\n)" for t in plan.tables]
    if status_tbl is not None and root.soft_delete_rule and "JEST" in root.soft_delete_rule:
        objnr = stg_column_name(root, "OBJNR")
        st_obj = stg_column_name(status_tbl, "OBJNR")
        st_stat = stg_column_name(status_tbl, "STAT")
        st_inact = stg_column_name(status_tbl, "INACT")
        cl = [stg_column_name(status_tbl, client)] if client and get_column(status_tbl, client) else []
        ctes.append(
            "status_flags as (\n    -- JEST is one row per status: aggregate to flags before joining (avoids fan-out)\n"
            f"    select {', '.join(cl + [st_obj])},\n"
            f"        boolor_agg({st_stat} = 'I0076' and {st_inact} is null) as is_deleted,\n"
            f"        boolor_agg({st_stat} = 'I0320' and {st_inact} is null) as is_inactive,\n"
            f"        max(_loaded_at) as _loaded_at\n"
            f"    from {{{{ ref('stg_{src}__jest') }}}}\n    group by {', '.join(cl + [st_obj])}\n)")
        status_join = ("left join status_flags as sf\n    on "
                       + (f"{ra}.{stg_column_name(root, client)} = sf.{cl[0]} and " if cl else "")
                       + f"{ra}.{objnr} = sf.{st_obj}")
    else:
        status_join = None

    sel, seen_names = [], set()
    for k in root.primary_key:
        n = stg_column_name(root, k)
        sel.append(f"        {ra}.{n}")
        seen_names.add(n)
    for c in columns:
        tname = next(t for t in plan.tables if t.upper() == c.table.upper())
        t = tables[tname]
        n = stg_column_name(t, c.column)
        out_name = snake(c.alias) if c.alias else n
        if out_name in seen_names:
            if n == out_name and tname == plan.root_table:
                continue
            out_name = f"{snake(t.name)}_{out_name}"
        seen_names.add(out_name)
        expr = f"{plan.aliases[tname]}.{n}"
        if t.table_class == "text":
            expr = f"coalesce({expr}, '')"
        sel.append(f"        {expr} as {out_name}" if (expr != f"{plan.aliases[tname]}.{out_name}") else f"        {expr}")
    if root.soft_delete_rule and "EXISTS" not in root.soft_delete_rule.upper():
        sel.append(f"        {ra}.is_deleted")
    elif status_join:
        sel.append("        coalesce(sf.is_deleted, false) as is_deleted")
        sel.append("        coalesce(sf.is_inactive, false) as is_inactive")
    loaded_parts = [f"{plan.aliases[t]}._loaded_at" for t in plan.tables] + (["sf._loaded_at"] if status_join else [])
    sel.append(f"        greatest_ignore_nulls({', '.join(loaded_parts)}) as _loaded_at")
    joins = []
    for e in plan.edges:
        cond = translate(e.condition_sql)
        rt = tables[e.right_table]
        if rt.default_filter:
            cond += f"\n   and {translate(rt.default_filter.replace('{alias}', e.right_alias))}"
        joins.append(f"-- {e.relationship_type} {e.cardinality} | {e.source_type} | {e.validation_status} "
                     f"| confidence {e.confidence:.2f}\n{e.join_type.lower()} join {e.right_alias}\n    on {cond}")
    if status_join:
        joins.append(status_join)
    where = []
    if root.default_filter:
        where.append(translate(root.default_filter.replace("{alias}", ra)))
    fanouts = [e for e in plan.edges if e.fans_out]
    root_keys = [f"{ra}.{stg_column_name(root, k)}" for k in root.primary_key]
    qualify = ""
    if fanouts:
        order = ", ".join(f"{e.right_alias}.{stg_column_name(tables[e.right_table], k)} desc"
                          for e in fanouts for k in e.uncovered_keys) or "1"
        qualify = f"\nqualify row_number() over (partition by {', '.join(root_keys)} order by {order}) = 1"
    int_sql = header + (
        f"-- Intermediate: joins for {entity} at grain {plan.root_table} ({', '.join(root.primary_key)}).\n"
        f"-- Every join below comes from the metadata repository; see comments for provenance.\n\n"
        "with\n\n" + ",\n\n".join(ctes) + ",\n\njoined as (\n\n    select\n" + ",\n".join(sel) +
        f"\n    from {ra}\n" + "\n".join(joins) +
        (f"\n    where {' and '.join(where)}" if where else "") + qualify + "\n\n)\n\nselect * from joined\n")
    proj.files[f"models/intermediate/{int_name}.sql"] = int_sql
    proj.model_names.append(int_name)
    int_cols = [re.split(r"\s+as\s+|\.", s.strip())[-1] for s in sel]

    # ------------------------------------------------------------------ marts
    main = rec.models[0]
    scd = opts.scd_type or main.scd_type
    nk_cols = [stg_column_name(root, k) for k in root.primary_key]
    sk = main.surrogate_key
    marts_yml = []
    strategy: IncrementalStrategy = incremental_strategy(erp, root)
    if main.kind == "dimension" and scd == "SCD2":
        snap = f"snap_{entity}"
        proj.files[f"snapshots/{snap}.sql"] = (
            f"{{% snapshot {snap} %}}\n\n{{{{\n    config(\n        unique_key=\"{sk}_nk\",\n"
            "        strategy='check',\n        check_cols='all',\n        invalidate_hard_deletes=True\n    )\n}}\n\n"
            f"select\n    {{{{ dbt_utils.generate_surrogate_key({nk_cols}) }}}} as {sk}_nk,\n    * exclude (_loaded_at)\n"
            f"from {{{{ ref('{int_name}') }}}}\n\n{{% endsnapshot %}}\n")
        mart_sql = header + (
            f"-- {main.name}: SCD Type 2 built from snapshot {snap}. {main.rationale}\n"
            "{{ config(materialized='table') }}\n\n"
            f"select\n    {{{{ dbt_utils.generate_surrogate_key(['{sk}_nk', 'dbt_valid_from']) }}}} as {sk},\n"
            f"    {sk}_nk,\n    " + ",\n    ".join(c for c in int_cols if c != "_loaded_at") + ",\n"
            "    dbt_valid_from as valid_from,\n    coalesce(dbt_valid_to, to_timestamp_ntz('9999-12-31')) as valid_to,\n"
            "    dbt_valid_to is null as is_current\n"
            f"from {{{{ ref('{snap}') }}}}\n")
        proj.model_names.append(snap)
        proj.notes.append(f"SCD2 via dbt snapshot `{snap}` (check strategy, hard deletes invalidated).")
    else:
        incremental = opts.materialization == "incremental" and strategy.strategy in ("merge", "append", "snapshot")
        if incremental:
            inc_strategy = "append" if strategy.strategy == "append" else "merge"
            cfg = (f"{{{{\n    config(\n        materialized='incremental',\n        unique_key='{sk}',\n"
                   f"        incremental_strategy='{inc_strategy}',\n        on_schema_change='append_new_columns'\n    )\n}}}}\n")
        else:
            cfg = "{{ config(materialized='table') }}\n"
        inc_filter = ("\n{% if is_incremental() %}\n"
                      "-- Lookback window re-processes late/date-only changes (watermark: "
                      f"{', '.join(strategy.watermark) or loaded_at}; reliable={strategy.watermark_reliable})\n"
                      "where _loaded_at > (select dateadd(day, -{{ var('lookback_days') }}, max(_loaded_at)) from {{ this }})\n"
                      "{% endif %}\n") if incremental else ""
        excl = "\n    and not is_deleted" if (opts.exclude_soft_deleted and "is_deleted" in int_cols) else ""
        mart_sql = header + (
            f"-- {main.name} ({main.kind}, {scd}). Grain: {main.grain}. {main.rationale}\n"
            f"-- Incremental strategy: {strategy.strategy}; change tracking: {strategy.change_tracking}\n"
            f"-- Hard deletes: {strategy.hard_delete}\n" + cfg + "\n"
            f"with src as (\n    select * from {{{{ ref('{int_name}') }}}}{inc_filter}\n)\n\n"
            f"select\n    {{{{ dbt_utils.generate_surrogate_key({nk_cols}) }}}} as {sk},\n    "
            + ",\n    ".join(int_cols) + "\nfrom src" + (f"\nwhere true{excl}" if excl else "") + "\n")
    proj.files[f"models/marts/{main.name}.sql"] = mart_sql
    proj.model_names.append(main.name)
    main_cols = [{"name": sk, "description": f"Surrogate key ({', '.join(nk_cols)}"
                  + (", valid_from" if scd == "SCD2" else "") + ")", "tests": ["unique", "not_null"]}]
    for c in int_cols:
        entry = {"name": c}
        if c in nk_cols and (not client or c != stg_column_name(root, client)):
            entry["tests"] = ["not_null"]
        if c in ("is_deleted", "is_inactive"):
            entry["tests"] = [{"accepted_values": {"values": [True, False], "quote": False}}]
        src_col = next((cc for cc in columns if (snake(cc.alias) if cc.alias else None) == c), None)
        if src_col:
            entry["description"] = f"{src_col.table}.{src_col.column}"
        main_cols.append(entry)
    main_yml = {"name": main.name, "description": f"{main.kind.title()} — {main.grain}. {main.rationale}",
                "columns": main_cols}
    if scd != "SCD2" and len(nk_cols) > 1:
        main_yml["tests"] = [{"dbt_utils.unique_combination_of_columns": {"combination_of_columns": nk_cols}}]
    marts_yml.append(main_yml)

    # Conformed dimensions for other entities (built from their own staging models)
    for spec in rec.models[1:]:
        if spec.kind != "dimension":
            continue
        anchor = tables[spec.source_tables[0]] if spec.source_tables[0] in tables else None
        for name in spec.source_tables:
            if tables[name].table_class in ("master", "config"):
                anchor = tables[name]
                break
        if anchor is None:
            continue
        a_alias = "a"
        nk = [stg_column_name(anchor, k) for k in anchor.primary_key]
        sel_cols = [f"{a_alias}.{stg_column_name(anchor, c.name)}" for c in anchor.columns
                    if c.business_name or c.is_pk]
        joins_d, i = [], 0
        for name in spec.source_tables:
            if name == anchor.name:
                continue
            e = next((e for e in plan.edges if {e.left_table, e.right_table} == {anchor.name, name}), None)
            if e is None:
                continue
            i += 1
            other = tables[name]
            al = f"t{i}"
            cond = e.condition_sql
            cond = cond.replace(f"{plan.aliases[anchor.name]}.", f"{a_alias}.").replace(f"{plan.aliases[name]}.", f"{al}.")
            cond = re.sub(rf"\b({a_alias}|{al})\.([A-Za-z0-9_/]+)",
                          lambda m: f"{m.group(1)}.{stg_column_name(anchor if m.group(1) == a_alias else other, m.group(2))}",
                          cond).replace(f"'{lang}'", "'{{ var(\"erp_language_key\") }}'")
            joins_d.append(f"left join {{{{ ref('stg_{src}__{name.lower()}') }}}} as {al}\n    on {cond}")
            sel_cols += [f"{al}.{stg_column_name(other, c.name)}" for c in other.columns
                         if c.business_name and not c.is_pk]
        dim_sk = spec.surrogate_key
        proj.files[f"models/marts/{spec.name}.sql"] = header + (
            f"-- {spec.name}: conformed SCD1 dimension. {spec.rationale}\n{{{{ config(materialized='table') }}}}\n\n"
            f"select\n    {{{{ dbt_utils.generate_surrogate_key({nk}) }}}} as {dim_sk},\n    "
            + ",\n    ".join(dict.fromkeys(sel_cols)) +
            f"\nfrom {{{{ ref('stg_{src}__{anchor.name.lower()}') }}}} as {a_alias}\n" + "\n".join(joins_d) + "\n"
            + (f"where not coalesce({a_alias}.is_deleted, false)\n" if anchor.soft_delete_rule and "EXISTS" not in anchor.soft_delete_rule.upper() else ""))
        proj.model_names.append(spec.name)
        marts_yml.append({"name": spec.name, "description": spec.rationale, "columns": [
            {"name": dim_sk, "tests": ["unique", "not_null"]}]})
        # relationships test from main mart to conformed dim when the natural key is carried
        fk_col = next((c for c in int_cols if c in [stg_column_name(anchor, k) for k in anchor.primary_key
                                                    if k.upper() not in (client, "SPRAS")]), None)
        anchor_nk = [stg_column_name(anchor, k) for k in anchor.primary_key if k.upper() not in (client, "SPRAS")]
        if len(anchor_nk) == 1:
            # find a column in the main mart that is joined to the anchor key
            for e in plan.edges:
                if e.right_table == anchor.name and len([j for j in e.join_columns if j["right"].upper() != client]) == 1:
                    j = next(j for j in e.join_columns if j["right"].upper() != client)
                    left_name = stg_column_name(tables[e.left_table], j["left"])
                    if left_name in int_cols:
                        for mc in main_cols:
                            if mc["name"] == left_name:
                                mc.setdefault("tests", []).append({"relationships": {
                                    "to": f"ref('{spec.name}')", "field": anchor_nk[0],
                                    "config": {"severity": "warn", "where": f"{left_name} is not null"}}})
        del fk_col

    proj.files["models/marts/_marts__models.yml"] = _yaml({"version": 2, "models": marts_yml})

    # ------------------------------------------------------------------ singular tests & analyses
    grain_cols = ", ".join(nk_cols + (["valid_from"] if scd == "SCD2" else []))
    proj.files[f"tests/assert_{main.name}_grain_is_unique.sql"] = (
        f"-- Fails if the grain ({grain_cols}) of {main.name} is duplicated.\n"
        f"select {grain_cols}, count(*) as n\nfrom {{{{ ref('{main.name}') }}}}\ngroup by {grain_cols}\nhaving count(*) > 1\n")
    date_cols = [c for c in int_cols if c.endswith(("_on", "_date"))]
    if date_cols:
        proj.files[f"tests/assert_{main.name}_dates_not_in_future.sql"] = (
            f"-- Data quality: creation/change dates must not be in the future.\nselect *\nfrom {{{{ ref('{main.name}') }}}}\nwhere "
            + "\n   or ".join(f"{c} > current_date()" for c in date_cols) + "\n")
    proj.files[f"tests/assert_{int_name}_row_count_matches_root.sql"] = (
        f"-- The intermediate model must not lose or multiply {plan.root_table} rows.\n"
        f"with a as (select count(*) as n from {{{{ ref('{int_name}') }}}}),\n"
        f"b as (select count(*) as n from {{{{ ref('stg_{src}__{plan.root_table.lower()}') }}}}"
        + (f" as {ra} where {' and '.join(where)}" if where else "") + ")\n"
        "select a.n as int_rows, b.n as root_rows from a cross join b where a.n <> b.n\n")
    if opts.generated_sql:
        proj.files["analyses/source_query.sql"] = opts.generated_sql
    proj.files["README.md"] = _readme(erp, plan, rec, opts, proj, strategy, loaded_at)
    return proj


def _needed_columns(t: ERPTable, plan: JoinPlan, selected: dict[str, set[str]], client: str) -> set[str]:
    needed = {k.upper() for k in t.primary_key}
    needed |= selected.get(t.name.upper(), set())
    for e in plan.edges:
        for jc in e.join_columns:
            if e.left_table == t.name:
                needed.add(jc["left"].upper())
            if e.right_table == t.name:
                needed.add(jc["right"].upper())
        if t.name in (e.left_table, e.right_table):
            needed |= {m.upper() for m in re.findall(r"\.([A-Z0-9_]+)\b", e.condition_sql)
                       if get_column(t, m) is not None}
    for expr in (t.default_filter or "", t.soft_delete_rule or ""):
        needed |= {m.upper() for m in re.findall(r"\b([A-Z][A-Z0-9_]+)\b", expr) if get_column(t, m) is not None}
    if t.name.upper() == "JEST":
        needed |= {"OBJNR", "STAT", "INACT"}
    if (t.change_tracking or {}).get("columns"):
        needed |= {c.upper() for c in t.change_tracking["columns"] if get_column(t, c) is not None}
    if client and get_column(t, client):
        needed.add(client)
    return needed


def _readme(erp, plan, rec, opts, proj, strategy, loaded_at) -> str:
    lines = [f"# {opts.project_name} — {erp.name}", "",
             "Generated by the ERP Data Modelling Intelligence Platform.", "",
             "## Layers", "",
             "| Layer | Models |", "|---|---|",
             f"| staging | {', '.join(m for m in proj.model_names if m.startswith('stg_'))} |",
             f"| intermediate | {', '.join(m for m in proj.model_names if m.startswith('int_'))} |",
             f"| marts | {', '.join(m for m in proj.model_names if m.startswith(('dim_', 'fct_')))} |",
             f"| snapshots | {', '.join(m for m in proj.model_names if m.startswith('snap_')) or '—'} |", "",
             "## Join provenance", "", "| Join | Type | Cardinality | Source | Confidence | Status |",
             "|---|---|---|---|---|---|"]
    for e in plan.edges:
        lines.append(f"| {e.left_table} → {e.right_table} | {e.join_type} | {e.cardinality} | {e.source_type} | "
                     f"{e.confidence:.2f} | {e.validation_status} |")
    lines += ["", "## Incremental loading", ""]
    for s in rec.strategies:
        lines.append(f"- **{s.table}** — {s.strategy}; key {s.unique_key}; watermark {s.watermark or '—'} "
                     f"(reliable: {s.watermark_reliable}); lookback {s.lookback}; deletes: {s.hard_delete}")
    lines += ["", f"Raw ingestion timestamp column: `{loaded_at}` (set `RAW_LOADED_AT_COLUMN`).",
              f"CDC delete column: `{opts.cdc_deleted_column or 'not configured'}`.", "",
              "## Run", "", "```bash", "dbt deps", "dbt build --select +" + rec.models[0].name, "```", "",
              "## Notes", ""] + [f"- {n}" for n in rec.notes + proj.notes + plan.warnings]
    return "\n".join(lines) + "\n"


def record_project(session: Session, erp: ERPSystem, proj: DbtProject, user: str, name: str) -> None:
    session.add(GeneratedArtifact(kind="dbt_project", name=name, erp_id=erp.id, created_by=user,
                                  meta={"files": len(proj.files), "models": proj.model_names}))
    for m in proj.model_names:
        session.add(GeneratedArtifact(kind="dbt_model", name=m, erp_id=erp.id, created_by=user,
                                      content=next((v for k, v in proj.files.items() if k.endswith(f"/{m}.sql")), None)))
    audit(session, user, "dbt.generate", "erp_system", erp.id, {"models": proj.model_names})
