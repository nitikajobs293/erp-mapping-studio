EMOJI_RE = re.compile(r"[\U0001F000-\U0001FAFF☀-➿⬀-⯿️]")


def _clean(s) -> str:
    return EMOJI_RE.sub("", str(s if s is not None else "")).strip()


def _public_df(df: pd.DataFrame) -> pd.DataFrame:
    return df[[c for c in df.columns if not str(c).startswith("_")]].map(_clean) if not df.empty else df


# --------------------------------------------------------------------------- bundle of content
def build_package(result: MappingResult, erp: ERPKnowledge, repo: KnowledgeRepository, sqls: dict[str, str],
                  dq: dict[str, str]) -> dict:
    medallion = ms.medallion_design(result, erp, repo)
    return {
        "mapping": _public_df(result.mapping_df()),
        "tables": _public_df(result.tables_df(erp)),
        "joins": _public_df(result.joins_df()),
        "grain": _public_df(ms.grain_and_keys(result, erp)),
        "classification": _public_df(ms.classify_tables(result, erp)),
        "staging": medallion["staging"], "silver": medallion["silver"], "gold": medallion["gold"],
        "ingestion": ms.ingestion_recommendations(result, erp),
        "warnings": result.warnings, "duplicate_risks": result.duplicate_risks,
        "sqls": sqls, "dq": dq,
        "dot": ms.mapping_dot(result, erp), "layer_dot": ms.layer_dot(result, erp, repo),
        "mermaid": ms.mermaid_er(result, erp),
    }


def _title(result: MappingResult) -> str:
    return f"{result.erp_name} - {result.business_object_label} Source-to-Target Mapping"


# --------------------------------------------------------------------------- Excel
def to_excel(result: MappingResult, pkg: dict) -> bytes:
    buf = io.BytesIO()
    with pd.ExcelWriter(buf, engine="openpyxl") as xw:
        cover = pd.DataFrame([
            ["Document", _title(result)], ["ERP", f"{result.erp_name} {result.erp_version}"],
            ["Business object", result.business_object_label], ["Anchor / grain table", result.anchor],
            ["Grain", result.grain], ["Effective grain (generated SQL)", result.effective_grain],
            ["Model type", result.model_type], ["Business key", ", ".join(result.business_key)],
            ["Generated", f"{datetime.now():%Y-%m-%d %H:%M}"], ["Generated by", APP_NAME],
            ["Disclaimer", "Mappings carry a confidence level. Validate 'Inferred' and 'Needs validation' items in the ERP."],
        ], columns=["Item", "Value"])
        cover.to_excel(xw, sheet_name="Overview", index=False)
        pkg["mapping"].to_excel(xw, sheet_name="Source-to-Target", index=False)
        pkg["tables"].to_excel(xw, sheet_name="Source Tables", index=False)
        pkg["joins"].to_excel(xw, sheet_name="Joins & Keys", index=False)
        pkg["grain"].to_excel(xw, sheet_name="Grain & Dedup", index=False)
        pkg["classification"].to_excel(xw, sheet_name="Fact-Dim Model", index=False)
        pd.concat([pkg["staging"], pkg["silver"], pkg["gold"]]).to_excel(xw, sheet_name="Medallion Layers", index=False)
        pd.DataFrame({"Warnings / validation notes": pkg["warnings"] + pkg["duplicate_risks"] or ["-"]}).to_excel(
            xw, sheet_name="Warnings", index=False)
        pd.DataFrame({"Ingestion recommendation": pkg["ingestion"]}).to_excel(xw, sheet_name="Ingestion", index=False)
        pd.DataFrame([{"Query type": k, "SQL": v} for k, v in pkg["sqls"].items()]).to_excel(xw, sheet_name="SQL", index=False)
        pd.DataFrame([{"Check": k, "SQL": v} for k, v in pkg["dq"].items()]).to_excel(xw, sheet_name="DQ Checks", index=False)
        from openpyxl.styles import Alignment, Font, PatternFill
        from openpyxl.utils import get_column_letter
        for ws in xw.book.worksheets:
            ws.freeze_panes = "A2"
            for cell in ws[1]:
                cell.font = Font(bold=True, color="FFFFFF")
                cell.fill = PatternFill("solid", fgColor="0D47A1")
                cell.alignment = Alignment(wrap_text=True, vertical="top")
            for i, col in enumerate(ws.columns, 1):
                width = max((len(str(c.value or "")) for c in col[:200]), default=10)
                ws.column_dimensions[get_column_letter(i)].width = min(max(12, width + 2), 70)
                for c in col[1:]:
                    c.alignment = Alignment(wrap_text=True, vertical="top")
            if ws.title == "Source-to-Target":
                ws.auto_filter.ref = ws.dimensions
                for row in ws.iter_rows(min_row=2):
                    conf = str(row[16].value or "") if len(row) > 16 else ""
                    color = {"Standard": "E8F5E9", "Confirmed": "E3F2FD", "Inferred": "FFF8E1",
                             "Needs": "FFEBEE", "AI": "F3E5F5", "Not": "EEEEEE"}
                    for key, fill in color.items():
                        if conf.startswith(key):
                            for c in row:
                                c.fill = PatternFill("solid", fgColor=fill)
    return buf.getvalue()


# --------------------------------------------------------------------------- Word
def to_docx(result: MappingResult, pkg: dict) -> bytes:
    from docx import Document
    from docx.enum.section import WD_ORIENT
    from docx.shared import Pt, RGBColor, Inches

    doc = Document()
    sec = doc.sections[0]
    sec.orientation = WD_ORIENT.LANDSCAPE
    sec.page_width, sec.page_height = sec.page_height, sec.page_width
    for s in doc.sections:
        s.left_margin = s.right_margin = Inches(0.6)
    style = doc.styles["Normal"]
    style.font.name = "Calibri"
    style.font.size = Pt(10)

    doc.add_heading(_title(result), 0)
    p = doc.add_paragraph()
    p.add_run(f"{APP_NAME} · generated {datetime.now():%Y-%m-%d %H:%M}").italic = True

    def table(df: pd.DataFrame, cols: list[str] | None = None, size: int = 8):
        df = df[cols] if cols else df
        if df.empty:
            doc.add_paragraph("(none)")
            return
        t = doc.add_table(rows=1, cols=len(df.columns))
        t.style = "Light Grid Accent 1"
        for i, c in enumerate(df.columns):
            t.rows[0].cells[i].text = str(c)
        for _, r in df.iterrows():
            cells = t.add_row().cells
            for i, v in enumerate(r):
                cells[i].text = _clean(v)
        for row in t.rows:
            for c in row.cells:
                for para in c.paragraphs:
                    for run in para.runs:
                        run.font.size = Pt(size)

    doc.add_heading("1. Scope and summary", 1)
    for k, v in [("ERP", f"{result.erp_name} {result.erp_version}"), ("Business object", result.business_object_label),
                 ("Anchor / grain table", result.anchor), ("Dataset grain", result.grain),
                 ("Effective grain of SQL", result.effective_grain), ("Model type", result.model_type),
                 ("Business key", ", ".join(result.business_key)),
                 ("Requested columns", ", ".join(result.requested_columns))]:
        para = doc.add_paragraph(style="List Bullet")
        para.add_run(f"{k}: ").bold = True
        para.add_run(_clean(v))

    doc.add_heading("2. Logical data model", 1)
    png = ms.render_dot(pkg["dot"], "png")
    if png:
        doc.add_picture(io.BytesIO(png), width=Inches(9.5))
    else:
        doc.add_paragraph("Diagram rendering requires Graphviz - see the .dot file in the bundle.")
    doc.add_heading("2.1 Source tables and their role", 2)
    table(pkg["tables"], ["Table", "Alias", "Description", "Primary Key", "Role in dataset", "Why required", "Confidence"])
    doc.add_heading("2.2 Joins, keys and cardinality", 2)
    table(pkg["joins"])
    doc.add_heading("2.3 Fact / dimension classification", 2)
    table(pkg["classification"])

    doc.add_heading("3. Grain, keys and deduplication", 1)
    table(pkg["grain"], size=9)

    doc.add_heading("4. Source-to-target mapping", 1)
    table(pkg["mapping"], ["Business Column", "Source Table", "Source Field", "Source Field Description", "Data Type",
                           "Join Condition", "Transformation", "Target Snowflake Column", "Availability",
                           "Confidence", "Validation Notes"], size=7)
    doc.add_paragraph("Full column detail (null handling, defaults, key roles, alternatives) is in the Excel mapping.").italic = True

    doc.add_heading("5. Snowflake layer design", 1)
    table(pd.concat([pkg["staging"], pkg["silver"], pkg["gold"]]))
    png2 = ms.render_dot(pkg["layer_dot"], "png")
    if png2:
        doc.add_picture(io.BytesIO(png2), width=Inches(9.5))

    doc.add_heading("6. Warnings and validation notes", 1)
    for w in pkg["warnings"] + pkg["duplicate_risks"] or ["None"]:
        doc.add_paragraph(_clean(w), style="List Bullet")

    doc.add_heading("7. Ingestion recommendations", 1)
    for w in pkg["ingestion"]:
        doc.add_paragraph(_clean(w), style="List Bullet")

    def code(text: str):
        para = doc.add_paragraph()
        run = para.add_run(text)
        run.font.name = "Consolas"
        run.font.size = Pt(7.5)
        run.font.color.rgb = RGBColor(0x1A, 0x23, 0x7E)

    doc.add_heading("8. Snowflake SQL", 1)
    for k in ("Deduplicated query", "Incremental load query", "CREATE OR REPLACE VIEW"):
        if k in pkg["sqls"]:
            doc.add_heading(k, 2)
            code(pkg["sqls"][k])
    doc.add_heading("9. Data quality and reconciliation queries", 1)
    for k, v in pkg["dq"].items():
        doc.add_heading(k, 2)
        code(v)
    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()


# --------------------------------------------------------------------------- PDF
def _latin(s) -> str:
    s = _clean(s).replace("→", "->").replace("—", "-").replace("–", "-").replace("’", "'") \
        .replace("“", '"').replace("”", '"').replace("≥", ">=").replace("≤", "<=")
    return s.encode("latin-1", errors="replace").decode("latin-1")


def to_pdf(result: MappingResult, pkg: dict) -> bytes:
    from fpdf import FPDF
    from fpdf.fonts import FontFace

    pdf = FPDF(orientation="L", unit="mm", format="A4")
    pdf.set_auto_page_break(True, margin=12)
    pdf.set_margins(10, 10, 10)
    pdf.add_page()
    pdf.set_font("Helvetica", "B", 16)
    pdf.multi_cell(0, 8, _latin(_title(result)), new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "I", 9)
    pdf.cell(0, 6, _latin(f"{APP_NAME} - generated {datetime.now():%Y-%m-%d %H:%M}"), new_x="LMARGIN", new_y="NEXT")

    def h(text, size=12):
        pdf.ln(2)
        pdf.set_font("Helvetica", "B", size)
        pdf.multi_cell(0, 7, _latin(text), new_x="LMARGIN", new_y="NEXT")
        pdf.set_font("Helvetica", "", 8)

    def para(text):
        pdf.set_font("Helvetica", "", 8.5)
        pdf.multi_cell(0, 4.5, _latin(text), new_x="LMARGIN", new_y="NEXT")

    def tbl(df: pd.DataFrame, cols=None, widths=None, size=6.5):
        df = df[cols] if cols else df
        if df.empty:
            para("(none)")
            return
        pdf.set_font("Helvetica", "", size)
        with pdf.table(col_widths=widths, text_align="LEFT", line_height=size * 0.55,
                       headings_style=FontFace(emphasis="BOLD", color=255, fill_color=(13, 71, 161))) as t:
            t.row([_latin(c) for c in df.columns])
            for _, r in df.iterrows():
                t.row([_latin(v)[:400] for v in r])

    h("1. Summary")
    for k, v in [("ERP", f"{result.erp_name} {result.erp_version}"), ("Business object", result.business_object_label),
                 ("Grain", result.grain), ("Effective grain", result.effective_grain),
                 ("Model type", result.model_type), ("Business key", ", ".join(result.business_key))]:
        para(f"{k}: {v}")
    png = ms.render_dot(pkg["dot"], "png")
    if png:
        h("2. Logical data model")
        pdf.image(io.BytesIO(png), w=270)
    h("3. Source tables")
    tbl(pkg["tables"], ["Table", "Description", "Primary Key", "Role in dataset", "Why required", "Confidence"],
        widths=(18, 40, 35, 25, 110, 30))
    h("4. Joins and cardinality")
    tbl(pkg["joins"], widths=(18, 22, 18, 70, 45, 15, 18, 25, 40))
    h("5. Grain, keys and deduplication")
    tbl(pkg["grain"], widths=(55, 222), size=7)
    pdf.add_page()
    h("6. Source-to-target mapping")
    tbl(pkg["mapping"], ["Business Column", "Source Table", "Source Field", "Source Field Description", "Join Condition",
                         "Transformation", "Target Snowflake Column", "Confidence", "Validation Notes"],
        widths=(25, 18, 30, 32, 45, 35, 30, 22, 40), size=6)
    h("7. Warnings")
    for w in pkg["warnings"] + pkg["duplicate_risks"]:
        para(f"- {w}")
    h("8. Ingestion recommendations")
    for w in pkg["ingestion"]:
        para(f"- {w}")
    pdf.add_page()
    h("9. Snowflake SQL - deduplicated query")
    pdf.set_font("Courier", "", 6.5)
    pdf.multi_cell(0, 3.2, _latin(pkg["sqls"].get("Deduplicated query", "")), new_x="LMARGIN", new_y="NEXT")
    return bytes(pdf.output())


# --------------------------------------------------------------------------- SQL / ZIP
def sql_script(pkg: dict, result: MappingResult) -> str:
    parts = [f"-- {_title(result)}\n-- All generated query variants. Review before running.\n"]
    for k, v in pkg["sqls"].items():
        if "sources.yml" in k:
            continue
        parts.append(f"\n-- {'=' * 100}\n-- {k}\n-- {'=' * 100}\n{v}\n")
    return "\n".join(parts)


def dq_script(pkg: dict) -> str:
    return "\n\n".join(f"-- {'=' * 80}\n-- {k}\n-- {'=' * 80}\n{v}" for k, v in pkg["dq"].items())


def grain_markdown(result: MappingResult, pkg: dict) -> str:
    md = [f"# Grain and relationship documentation - {result.erp_name} {result.business_object_label}\n"]
    md.append(pkg["grain"].to_markdown(index=False))
    md.append("\n## Joins\n" + pkg["joins"].to_markdown(index=False))
    md.append("\n## Fact / dimension classification\n" + pkg["classification"].to_markdown(index=False))
    md.append("\n## Ingestion recommendations\n" + "\n".join(f"- {x}" for x in pkg["ingestion"]))
    return "\n".join(md)


def to_zip(result: MappingResult, pkg: dict) -> bytes:
    base = re.sub(r"[^A-Za-z0-9]+", "_", f"{result.erp_id}_{result.business_object}").strip("_")
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr(f"{base}_mapping.xlsx", to_excel(result, pkg))
        z.writestr(f"{base}_technical_design.docx", to_docx(result, pkg))
        z.writestr(f"{base}_technical_design.pdf", to_pdf(result, pkg))
        z.writestr(f"{base}_all_queries.sql", sql_script(pkg, result))
        z.writestr(f"{base}_dq_checks.sql", dq_script(pkg))
        z.writestr(f"{base}_grain_and_relationships.md", grain_markdown(result, pkg))
        z.writestr(f"{base}_er_diagram.dot", pkg["dot"])
        z.writestr(f"{base}_er_diagram.mmd", pkg["mermaid"])
        z.writestr(f"{base}_layers.dot", pkg["layer_dot"])
        z.writestr("dbt/sources.yml", pkg["sqls"].get("dbt sources.yml", ""))
        z.writestr(f"dbt/models/slv_{base.lower()}.sql", pkg["sqls"].get("dbt model SQL", ""))
        for fmt in ("png", "svg"):
            img = ms.render_dot(pkg["dot"], fmt)
            if img:
                z.writestr(f"{base}_er_diagram.{fmt}", img)
        z.writestr("ingestion_recommendations.md", "\n".join(f"- {x}" for x in pkg["ingestion"]))
    return buf.getvalue()


def comparison_excel(matrix: pd.DataFrame, details: pd.DataFrame, highlights: dict, ddl: str, union_sql: str) -> bytes:
    buf = io.BytesIO()
    with pd.ExcelWriter(buf, engine="openpyxl") as xw:
        matrix.map(_clean).to_excel(xw, sheet_name="Comparison Matrix", index=False)
        details.to_excel(xw, sheet_name="Field Details", index=False)
        rows = [{"Category": k, "Item": _clean(i)} for k, v in highlights.items() for i in (v or ["-"])]
        pd.DataFrame(rows).to_excel(xw, sheet_name="Highlights", index=False)
        pd.DataFrame({"Canonical DDL": [ddl], "Union SQL": [union_sql]}).to_excel(xw, sheet_name="Canonical Model", index=False)
    return buf.getvalue()


def comparison_docx(title: str, matrix: pd.DataFrame, highlights: dict, ddl: str, union_sql: str) -> bytes:
    from docx import Document
    from docx.enum.section import WD_ORIENT
    from docx.shared import Pt
    doc = Document()
    sec = doc.sections[0]
    sec.orientation = WD_ORIENT.LANDSCAPE
    sec.page_width, sec.page_height = sec.page_height, sec.page_width
    doc.add_heading(title, 0)
    t = doc.add_table(rows=1, cols=len(matrix.columns))
    t.style = "Light Grid Accent 1"
    for i, c in enumerate(matrix.columns):
        t.rows[0].cells[i].text = str(c)
    for _, r in matrix.iterrows():
        cells = t.add_row().cells
        for i, v in enumerate(r):
            cells[i].text = _clean(v)
    for row in t.rows:
        for c in row.cells:
            for p in c.paragraphs:
                for run in p.runs:
                    run.font.size = Pt(8)
    for k, v in highlights.items():
        doc.add_heading(k, 2)
        for i in v or ["-"]:
            doc.add_paragraph(_clean(i), style="List Bullet")
    doc.add_heading("Canonical Snowflake model", 1)
    for text in (ddl, union_sql):
        run = doc.add_paragraph().add_run(text)
        run.font.name = "Consolas"
        run.font.size = Pt(7)
    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()
